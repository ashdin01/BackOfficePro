"""Warehouse Order PDF (warehouse -> shop transfer).

Same look as the PO PDFs (utils/po_pdf.py): landscape A4, black-and-white,
print-safe, store header, grey-header lines table and a
"ref | Page x of y" footer.
"""
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_RIGHT
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    HRFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
)

C_BLACK  = colors.HexColor("#111111")
C_GREY   = colors.HexColor("#555555")
C_LGREY  = colors.HexColor("#f2f2f2")
C_BORDER = colors.HexColor("#aaaaaa")


def _fmt_qty(q) -> str:
    return str(int(q)) if float(q) == int(q) else f"{q:g}"


def _pack(ln):
    """(pack_qty, pack_unit) for a line, defaulting to a single each."""
    try:
        pq = int(ln.get("pack_qty") or 1)
    except (TypeError, ValueError):
        pq = 1
    return max(pq, 1), (ln.get("pack_unit") or "EA")


def _cartons_str(qty, pack_qty, pack_unit) -> str:
    """PO convention: 'N cartons' when the product has a pack size, else 'N each'."""
    if pack_qty > 1:
        n = float(qty) / pack_qty
        n_txt = str(int(n)) if n == int(n) else f"{n:.2f}".rstrip("0").rstrip(".")
        return f"{n_txt} carton" + ("" if n == 1 else "s")
    word = "each" if pack_unit.upper() == "EA" else pack_unit.lower()
    return f"{_fmt_qty(qty)} {word}"


def order_ref(created_at) -> str:
    return f"WO-{created_at:%Y%m%d-%H%M}"


def _styles():
    def ps(name, **kw):
        return ParagraphStyle(name, textColor=kw.pop("textColor", C_BLACK), **kw)
    return {
        "title":    ps("title", fontSize=18, fontName="Helvetica-Bold", spaceAfter=2),
        "body":     ps("body", fontSize=9, fontName="Helvetica", leading=13),
        "big":      ps("big", fontSize=9, fontName="Helvetica", leading=11),
        "big_ctr":  ps("big_ctr", fontSize=9, fontName="Helvetica-Bold", alignment=TA_CENTER),
        "big_ctr_n": ps("big_ctr_n", fontSize=9, fontName="Helvetica", alignment=TA_CENTER),
        "small":    ps("small", fontSize=8, fontName="Helvetica", textColor=C_GREY),
        "hdr":      ps("hdr", fontSize=9, fontName="Helvetica-Bold"),
        "hdr_ctr":  ps("hdr_ctr", fontSize=9, fontName="Helvetica-Bold", alignment=TA_CENTER),
        "doc_label": ps("doc_label", fontSize=9, leading=11, fontName="Helvetica-Bold", alignment=TA_RIGHT),
        "doc_date": ps("doc_date", fontSize=9, leading=11, fontName="Helvetica", alignment=TA_RIGHT),
        "doc_ref":  ps("doc_ref", fontSize=16, leading=19, fontName="Helvetica-Bold", alignment=TA_RIGHT),
        "tot_label": ps("tot_label", fontSize=12, fontName="Helvetica-Bold", alignment=TA_RIGHT),
        "tot_value": ps("tot_value", fontSize=12, fontName="Helvetica-Bold", alignment=TA_RIGHT),
        "footer":   ps("footer", fontSize=7, fontName="Helvetica", textColor=C_GREY, alignment=TA_CENTER),
    }


def _numbered_canvas_cls(ref):
    from reportlab.pdfgen import canvas as _canvas

    class _NumberedCanvas(_canvas.Canvas):
        def __init__(self, *a, **kw):
            super().__init__(*a, **kw)
            self._saved = []

        def showPage(self):
            self._saved.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            total = len(self._saved)
            for state in self._saved:
                self.__dict__.update(state)
                self.setFont("Helvetica", 7)
                self.setFillColor(C_GREY)
                w, _ = self._pagesize
                self.drawCentredString(w / 2, 8 * mm, f"Generated by BackOfficePro  |  {datetime.now():%d/%m/%Y %H:%M}  |  {ref}  |  Page {self._pageNumber} of {total}")
                super().showPage()
            super().save()

    return _NumberedCanvas


def build_warehouse_order_pdf(path: str, lines: list, created_at, store_name: str = "",
                              notes: str = "", store_details: str = "", spare_lines: int = 2) -> None:
    """lines: [{barcode, description, qty}] -> landscape A4 PDF at path.

    spare_lines blank, numbered rows are added after the items (not counted in
    totals) so items not yet on the Warehouse Order list can be written in by hand.
    """
    st = _styles()
    ref = order_ref(created_at)
    doc = SimpleDocTemplate(
        path, pagesize=landscape(A4),
        leftMargin=18 * mm, rightMargin=18 * mm, topMargin=10 * mm, bottomMargin=14 * mm,
        title=f"Warehouse Order {ref}",
    )
    W = landscape(A4)[0] - 36 * mm
    story = []

    # Header: store name left, document title + reference right
    header = Table([[Paragraph(store_name or "Warehouse Order", st["title"]),
                     [Paragraph("WAREHOUSE ORDER", st["doc_label"]),
                      Paragraph(ref, st["doc_ref"]),
                      Paragraph(f"{created_at:%d/%m/%Y %H:%M}", st["doc_date"])]]],
                   colWidths=[W * 0.6, W * 0.4])
    header.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                                ("BOTTOMPADDING", (0, 0), (-1, -1), 0)]))
    story.append(header)
    if store_details:
        story.append(Paragraph(store_details, st["small"]))
    story.append(HRFlowable(width="100%", thickness=1.5, color=C_BLACK, spaceAfter=5))

    total_units = sum(float(ln["qty"]) for ln in lines)
    if notes:
        story.append(Paragraph(f"<b>Notes:</b> {notes}", st["body"]))
        story.append(Spacer(1, 4))

    # Lines table (same Pack / Order / Total Units convention as the PO PDFs).
    # "Picked" is left blank to tick off while picking.
    col_widths = [W * 0.04, W * 0.13, W * 0.43, W * 0.08, W * 0.10, W * 0.10, W * 0.12]
    data = [[Paragraph("#", st["hdr"]), Paragraph("Barcode", st["hdr"]),
             Paragraph("Description", st["hdr"]), Paragraph("Pack", st["hdr"]),
             Paragraph("Order<br/>(cartons)", st["hdr_ctr"]),
             Paragraph("Order<br/>(units)", st["hdr_ctr"]),
             Paragraph("Picked", st["hdr_ctr"])]]
    for i, ln in enumerate(lines, 1):
        pq, pu = _pack(ln)
        pack_str = f"{pq} x {pu}" if pq > 1 else pu
        data.append([Paragraph(str(i), st["big"]), Paragraph(str(ln["barcode"]), st["big"]),
                     Paragraph(ln["description"], st["big"]), Paragraph(pack_str, st["big"]),
                     Paragraph(_cartons_str(ln["qty"], pq, pu), st["big_ctr_n"]),
                     Paragraph(_fmt_qty(ln["qty"]), st["big_ctr"]), ""])
    row_heights = [None] * len(data)
    for j in range(spare_lines):
        data.append([Paragraph(str(len(lines) + j + 1), st["big"]), "", "", "", "", "", ""])
        row_heights.append(19)
    tbl = Table(data, colWidths=col_widths, rowHeights=row_heights, repeatRows=1)
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), C_LGREY),
        ("TOPPADDING", (0, 0), (-1, 0), 4), ("BOTTOMPADDING", (0, 0), (-1, 0), 4),
        ("TOPPADDING", (0, 1), (-1, -1), 2), ("BOTTOMPADDING", (0, 1), (-1, -1), 2),
        ("LEFTPADDING", (0, 0), (-1, -1), 4), ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.25, C_BORDER),
        ("BOX", (0, 0), (-1, -1), 0.75, C_BLACK),
    ]))
    story += [tbl, Spacer(1, 3)]

    # Cartons only count for lines that have a pack size (PO convention).
    total_ctn = sum(float(ln["qty"]) / _pack(ln)[0] for ln in lines if _pack(ln)[0] > 1)
    ctn_txt = str(int(total_ctn)) if total_ctn == int(total_ctn) else f"{total_ctn:.2f}".rstrip("0").rstrip(".")
    totals = Table([[Paragraph("ORDER QTY:", st["tot_label"]),
                     Paragraph(f"{ctn_txt} ctn / {_fmt_qty(total_units)} units", st["tot_value"])]],
                   colWidths=[W * 0.76, W * 0.24])
    totals.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LINEABOVE", (0, 0), (-1, 0), 1, C_BLACK), ("LINEBELOW", (0, 0), (-1, 0), 0.75, C_BLACK),
        ("TOPPADDING", (0, 0), (-1, 0), 4), ("BOTTOMPADDING", (0, 0), (-1, 0), 4),
        ("BACKGROUND", (0, 0), (-1, 0), C_LGREY),
    ]))
    story.append(totals)

    doc.build(story, canvasmaker=_numbered_canvas_cls(ref))
